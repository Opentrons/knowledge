"""Canonical document models extracted from rendered MkDocs HTML.

One ``CanonicalDocument`` is one rendered documentation page. Sections are
defined by the page's rendered headings and hold an ordered list of content
blocks. Sections are source structure, not retrieval chunks: chunkers should
read these records and decide their own boundaries.
"""

from __future__ import annotations

from typing import Annotated, Any, Final, Literal

from pydantic import BaseModel, ConfigDict, Field

CANONICAL_SCHEMA_ID: Final = "opentrons-knowledge.canonical-docs"
CANONICAL_SCHEMA_VERSION = 1


class CanonicalModel(BaseModel):
    """Base model for canonical records (strict, stable field order)."""

    model_config = ConfigDict(extra="forbid")


# ---------------------------------------------------------------------------
# Content blocks
# ---------------------------------------------------------------------------


class ParagraphBlock(CanonicalModel):
    """Running text rendered as Markdown-style inline text.

    Inline conventions: backticks for code, ``**bold**``, ``*emphasis*``,
    ``[label](href)`` for links, ``![alt](src)`` for inline images, and the
    original ``:icon-name:`` shortcode for inline icons when it can be recovered.
    """

    type: Literal["paragraph"] = "paragraph"
    text: str


class HeadingBlock(CanonicalModel):
    """A heading nested inside a container (tab, admonition, list).

    Headings at the top level of the article start new sections instead.
    """

    type: Literal["heading"] = "heading"
    level: int
    text: str
    anchor: str | None = None


class CodeBlock(CanonicalModel):
    """A complete code block, verbatim, without syntax-highlighting markup."""

    type: Literal["code"] = "code"
    language: str | None = None
    code: str
    title: str | None = None
    role: Literal["signature"] | None = Field(
        default=None,
        description="'signature' for API signatures generated by mkdocstrings.",
    )


class ListItem(CanonicalModel):
    blocks: list[Block] = Field(default_factory=list)


class ListBlock(CanonicalModel):
    type: Literal["list"] = "list"
    ordered: bool
    start: int | None = None
    items: list[ListItem] = Field(default_factory=list)


class TableCell(CanonicalModel):
    text: str
    header: bool = False
    rowspan: int = 1
    colspan: int = 1


class TableRow(CanonicalModel):
    header: bool = False
    cells: list[TableCell] = Field(default_factory=list)


class TableBlock(CanonicalModel):
    """A table with spans preserved as authored (cells are not expanded)."""

    type: Literal["table"] = "table"
    caption: str | None = None
    rows: list[TableRow] = Field(default_factory=list)


class AdmonitionBlock(CanonicalModel):
    """Note, warning, tip, and other callouts (including collapsible details)."""

    type: Literal["admonition"] = "admonition"
    kind: str
    title: str | None = None
    collapsible: bool = False
    blocks: list[Block] = Field(default_factory=list)


class Tab(CanonicalModel):
    label: str
    blocks: list[Block] = Field(default_factory=list)


class TabsBlock(CanonicalModel):
    """A content tab set; each tab keeps its label and its own blocks."""

    type: Literal["tabs"] = "tabs"
    tabs: list[Tab] = Field(default_factory=list)


class ImageBlock(CanonicalModel):
    type: Literal["image"] = "image"
    src: str
    url: str
    alt: str = ""
    title: str | None = None


class FigureBlock(CanonicalModel):
    type: Literal["figure"] = "figure"
    caption: str | None = None
    blocks: list[Block] = Field(default_factory=list)


class QuoteBlock(CanonicalModel):
    type: Literal["quote"] = "quote"
    blocks: list[Block] = Field(default_factory=list)


class HtmlBlock(CanonicalModel):
    """Fallback for markup that has no faithful structured representation."""

    type: Literal["html"] = "html"
    html: str
    text: str = ""
    reason: str


Block = Annotated[
    ParagraphBlock
    | HeadingBlock
    | CodeBlock
    | ListBlock
    | TableBlock
    | AdmonitionBlock
    | TabsBlock
    | ImageBlock
    | FigureBlock
    | QuoteBlock
    | HtmlBlock,
    Field(discriminator="type"),
]


# ---------------------------------------------------------------------------
# Sections, references, documents
# ---------------------------------------------------------------------------


class ApiObject(CanonicalModel):
    """mkdocstrings metadata for a section generated from Python source."""

    qualified_name: str
    kind: str
    labels: list[str] = Field(default_factory=list)


class CanonicalSection(CanonicalModel):
    """A heading-delimited region of a page, in document order."""

    section_id: str
    document_id: str
    ordinal: int
    level: int
    title: str
    anchor: str | None = None
    url: str
    heading_path: list[str]
    parent_section_id: str | None = None
    child_section_ids: list[str] = Field(default_factory=list)
    previous_section_id: str | None = None
    next_section_id: str | None = None
    api: ApiObject | None = None
    blocks: list[Block] = Field(default_factory=list)
    content_hash: str


class LinkRef(CanonicalModel):
    section_id: str
    text: str
    href: str
    url: str
    internal: bool
    target_page_path: str | None = None
    target_anchor: str | None = None


class ImageRef(CanonicalModel):
    section_id: str
    src: str
    url: str
    alt: str = ""
    site_path: str | None = None
    source_path: str | None = None


class SourceRef(CanonicalModel):
    """Where the page came from in the documentation repository."""

    repository: str
    commit: str
    ref: str | None = None
    markdown_path: str | None = None
    markdown_url: str | None = None
    markdown_sha256: str | None = None
    front_matter: dict[str, Any] = Field(default_factory=dict)


class RenderedRef(CanonicalModel):
    html_path: str
    html_sha256: str
    generator: str | None = None


class CanonicalDocument(CanonicalModel):
    """One rendered documentation page."""

    schema_version: int = CANONICAL_SCHEMA_VERSION
    document_id: str
    page_path: str
    url: str
    title: str
    page_title: str | None = None
    description: str | None = None
    project: str | None = None
    nav_path: list[str] = Field(default_factory=list)
    source: SourceRef
    rendered: RenderedRef
    sections: list[CanonicalSection]
    links: list[LinkRef] = Field(default_factory=list)
    images: list[ImageRef] = Field(default_factory=list)
    search_exclude: bool = Field(
        default=False,
        description="Page front matter sets search.exclude, matching the MkDocs search index.",
    )
    content_hash: str


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------


class CanonicalArtifact(CanonicalModel):
    path: str
    format: str = "jsonl"
    compression: str = "zstd"
    record_count: int
    sha256: str
    uncompressed_sha256: str


class CanonicalDocumentEntry(CanonicalModel):
    document_id: str
    page_path: str
    title: str
    markdown_path: str | None = None
    section_count: int
    search_exclude: bool = False
    content_hash: str


class ExcludedPage(CanonicalModel):
    html_path: str
    reason: str


class CanonicalSourceInfo(CanonicalModel):
    repository: str
    ref: str | None = None
    commit: str
    dirty: bool = False
    mkdocs_extra: dict[str, Any] = Field(default_factory=dict)


class CanonicalBuildInfo(CanonicalModel):
    mkdocs_config: str
    working_directory: str
    setup_command: list[str]
    build_command: list[str]
    environment: dict[str, str] = Field(default_factory=dict)
    site_dir: str
    base_url: str
    generator: str | None = None
    prebuilt_site: bool = False
    modified_files: list[str] = Field(
        default_factory=list,
        description="Tracked files rewritten by the docs build itself (e.g. a stale uv.lock).",
    )


class CanonicalExtractorInfo(CanonicalModel):
    name: str
    version: int
    builder_version: str
    html_parser: str
    dependencies: dict[str, str] = Field(default_factory=dict)
    icon_shortcodes: int = 0


class CanonicalManifest(CanonicalModel):
    schema_id: Literal["opentrons-knowledge.canonical-docs"] = CANONICAL_SCHEMA_ID
    schema_version: int = CANONICAL_SCHEMA_VERSION
    corpus_version: str | None = None
    source: CanonicalSourceInfo
    build: CanonicalBuildInfo
    extractor: CanonicalExtractorInfo
    artifacts: list[CanonicalArtifact]
    document_count: int
    section_count: int
    block_counts: dict[str, int] = Field(default_factory=dict)
    documents: list[CanonicalDocumentEntry]
    excluded_pages: list[ExcludedPage] = Field(default_factory=list)


for _model in (ListItem, AdmonitionBlock, Tab, FigureBlock, QuoteBlock, CanonicalSection):
    _model.model_rebuild()


CANONICAL_JSON_SCHEMAS: Final = {
    "canonical-document.schema.json": CanonicalDocument,
    "canonical-manifest.schema.json": CanonicalManifest,
}


def canonical_json_schema(model: type[BaseModel], filename: str) -> dict[str, object]:
    """Return the published JSON Schema for a record model.

    Args:
        model: Root model, for example ``CanonicalDocument``.
        filename: Schema file name under ``schemas/``, used for ``$id``.

    Returns:
        Draft 2020-12 schema generated from the Pydantic model.
    """
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://opentrons.com/schemas/opentrons-knowledge/{filename}",
        **model.model_json_schema(mode="serialization"),
    }
